using System.Globalization;
using System.Xml.Linq;
using BannerlordEnvironmentManager.Core.Localization;

namespace BannerlordEnvironmentManager.Core.Modules;

public sealed record ManagerRegistrationResult(bool Done, string Message, string? Path = null);

// Registers a BEM-managed game folder with another mod manager by writing that manager's own
// configuration, never by launching it or touching its other data:
//
//   Mod Organizer 2: an instance folder with ModOrganizer.ini, which MO2's instance manager lists
//   (gameName, gamePath, selected_profile, as MO2 writes them), plus the empty mods, profiles\Default,
//   downloads and overwrite folders MO2 expects.
//
//   Novus Launcher: a preset XML in its Presets folder naming the enabled modules and their versions,
//   in the shape Novus writes its own Default and Last Used presets.
//
//   Vortex: not written. Vortex keeps its game list in a LevelDB store (state.v2) that it holds open
//   and rewrites, so editing it from outside risks the owner's whole Vortex profile; Vortex finds the
//   game itself from Steam or by "Manually Add" in its Games tab.
public static class ManagerRegistration
{
    public const string Mo2GameName = "Mount & Blade II: Bannerlord";

    private static readonly string[] NovusReserved = ["default", "last used", "lastused"];

    public static ManagerRegistrationResult RegisterWithMo2(string mo2InstancesRoot, string instanceName, string gamePath)
    {
        if (string.IsNullOrWhiteSpace(mo2InstancesRoot) || string.IsNullOrWhiteSpace(gamePath))
            return Fail("Core.Modules.Managers.Mo2.NoFolder");

        var safe = SafeName(instanceName);

        if (safe.Length == 0)
            return Fail("Core.Modules.Managers.NoName");

        try
        {
            var folder = Path.Combine(mo2InstancesRoot, safe);
            Directory.CreateDirectory(folder);

            foreach (var sub in new[] { "mods", "downloads", "overwrite", Path.Combine("profiles", "Default") })
                Directory.CreateDirectory(Path.Combine(folder, sub));

            var modlist = Path.Combine(folder, "profiles", "Default", "modlist.txt");
            if (!File.Exists(modlist))
                File.WriteAllText(modlist, "# This file was automatically generated by Mod Organizer.\r\n");

            var ini = Path.Combine(folder, "ModOrganizer.ini");
            var existing = File.Exists(ini) ? File.ReadAllLines(ini).ToList() : [];
            File.WriteAllLines(ini, SetGeneral(existing, gamePath));

            return new ManagerRegistrationResult(true, Strings.Current.Format("Core.Modules.Managers.Mo2.Done", folder), folder);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or ArgumentException or NotSupportedException)
        {
            return new ManagerRegistrationResult(false, Strings.Current.Format("Core.Modules.Managers.Failed", ex.Message));
        }
    }

    // Sets gameName, gamePath and selected_profile under [General], leaving every other line, key and
    // section of an existing ModOrganizer.ini as it was.
    public static IReadOnlyList<string> SetGeneral(IReadOnlyList<string> lines, string gamePath)
    {
        var wanted = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
        {
            ["gameName"] = Mo2GameName,
            ["gamePath"] = "@ByteArray(" + gamePath.TrimEnd('\\', '/').Replace("\\", "\\\\") + ")",
            ["selected_profile"] = "@ByteArray(Default)",
        };

        var result = new List<string>();
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var inGeneral = false;
        var sawGeneral = false;

        void FlushMissing()
        {
            foreach (var pair in wanted.Where(p => !seen.Contains(p.Key)))
                result.Add($"{pair.Key}={pair.Value}");
        }

        foreach (var line in lines)
        {
            var trimmed = line.Trim();

            if (trimmed.StartsWith('['))
            {
                if (inGeneral)
                    FlushMissing();

                inGeneral = trimmed.Equals("[General]", StringComparison.OrdinalIgnoreCase);
                sawGeneral |= inGeneral;
                result.Add(line);
                continue;
            }

            var equals = trimmed.IndexOf('=');

            if (inGeneral && equals > 0 && wanted.TryGetValue(trimmed[..equals], out var value))
            {
                seen.Add(trimmed[..equals]);
                result.Add($"{trimmed[..equals]}={value}");
                continue;
            }

            result.Add(line);
        }

        if (inGeneral)
            FlushMissing();

        if (!sawGeneral)
        {
            result.Insert(0, "[General]");
            result.InsertRange(1, wanted.Select(p => $"{p.Key}={p.Value}"));
        }

        return result;
    }

    // The first of these folders that is a Novus Launcher install (its exe beside a Presets folder).
    public static string? FindNovus(IEnumerable<string> candidateFolders)
    {
        foreach (var folder in candidateFolders.Where(f => !string.IsNullOrWhiteSpace(f)))
        {
            try
            {
                if (File.Exists(Path.Combine(folder, "NovusLauncher.exe")) && Directory.Exists(Path.Combine(folder, "Presets")))
                    return folder;
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or ArgumentException)
            {
            }
        }

        return null;
    }

    public static ManagerRegistrationResult RegisterWithNovus(
        string? novusFolder, string presetName, IEnumerable<(string Id, string Version)> modules)
    {
        ArgumentNullException.ThrowIfNull(modules);

        if (string.IsNullOrWhiteSpace(novusFolder) || !Directory.Exists(Path.Combine(novusFolder, "Presets")))
            return Fail("Core.Modules.Managers.Novus.NotFound");

        var safe = SafeName(presetName);

        if (safe.Length == 0 || NovusReserved.Contains(safe.ToLowerInvariant()))
            return Fail("Core.Modules.Managers.NoName");

        try
        {
            var preset = new XElement("Preset",
                new XAttribute("Name", safe),
                new XAttribute("CreatedBy", "Bannerlord Environment Manager"),
                new XAttribute("LastUpdated", DateTime.Now.ToString("dd/MM/yyyy", CultureInfo.InvariantCulture)),
                modules.Select(m => new XElement("PresetModule",
                    new XAttribute("Id", m.Id),
                    new XAttribute("RequiredVersion", m.Version),
                    new XAttribute("URL", string.Empty))));

            var file = Path.Combine(novusFolder, "Presets", safe + ".xml");
            File.WriteAllText(file, preset.ToString() + Environment.NewLine);

            return new ManagerRegistrationResult(true, Strings.Current.Format("Core.Modules.Managers.Novus.Done", safe), file);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or ArgumentException or NotSupportedException)
        {
            return new ManagerRegistrationResult(false, Strings.Current.Format("Core.Modules.Managers.Failed", ex.Message));
        }
    }

    public static ManagerRegistrationResult VortexNotWritten() => Fail("Core.Modules.Managers.Vortex.Manual");

    public static string SafeName(string? name)
    {
        var cleaned = new string([.. (name ?? string.Empty).Where(c => !Path.GetInvalidFileNameChars().Contains(c))]).Trim().TrimEnd('.');
        return cleaned;
    }

    private static ManagerRegistrationResult Fail(string key) => new(false, Strings.Current[key]);
}
