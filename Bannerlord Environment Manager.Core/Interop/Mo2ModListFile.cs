using BannerlordEnvironmentManager.Core.LoadOrder;
using BannerlordEnvironmentManager.Core.Localization;

namespace BannerlordEnvironmentManager.Core.Interop;

// Mod Organizer 2's profile modlist.txt: "+Name" enabled, "-Name" disabled, "*Name" a mod the game
// itself provides, "#" a comment. The file lists the HIGHEST priority first. Bannerlord loads later
// modules over earlier ones, so a higher priority is a later load order position: the file is the load
// order read upward, and both directions here reverse it.
//
// A line names an MO2 mod folder, not a module. The folder-to-module map (mods\<name>\Modules\<Id>)
// says which module ids each folder carries; a folder with none (a texture pack) is not part of a
// Bannerlord load order and is skipped, and a folder carrying several expands to all of them.
public static class Mo2ModListFile
{
    public const string FileName = "modlist.txt";

    public const string Header = "# This file was automatically generated by Mod Organizer.";

    // Whether the text is a modlist.txt: at least one +/- line and nothing else but comments, blanks
    // and "*" lines.
    public static bool Looks(string text)
    {
        ArgumentNullException.ThrowIfNull(text);

        var any = false;

        foreach (var raw in text.TrimStart('﻿').Split('\n'))
        {
            var line = raw.Trim();

            if (line.Length == 0 || line[0] == '#')
                continue;

            if (line.Length < 2 || line[0] is not ('+' or '-' or '*'))
                return false;

            any |= line[0] != '*';
        }

        return any;
    }

    public static LoadOrderFileRead Read(string text, IReadOnlyDictionary<string, IReadOnlyList<string>>? folderModules = null)
    {
        ArgumentNullException.ThrowIfNull(text);

        var lines = ParseLines(text);

        if (lines.Count == 0)
            return LoadOrderFileRead.Unreadable(Strings.Current["Core.Interop.Mo2ModListFile.NoModLines"]);

        var entries = new List<LoadOrderFileEntry>();
        var unreadable = 0;
        var map = folderModules is null
            ? null
            : new Dictionary<string, IReadOnlyList<string>>(folderModules, StringComparer.OrdinalIgnoreCase);

        // Reverse: the last line has the lowest priority, so it loads first.
        for (var i = lines.Count - 1; i >= 0; i--)
        {
            var (enabled, name) = lines[i];

            if (name.EndsWith(ModOrganizerCsvFile.SeparatorSuffix, StringComparison.OrdinalIgnoreCase))
                continue;

            if (map is null)
            {
                // No instance to look in: the name stands for itself and the importer matches it by title.
                entries.Add(new LoadOrderFileEntry(name, string.Empty, enabled, name));
                continue;
            }

            if (!map.TryGetValue(name, out var modules) || modules.Count == 0)
            {
                unreadable++;
                continue;
            }

            foreach (var module in modules)
                entries.Add(new LoadOrderFileEntry(module, string.Empty, enabled, name));
        }

        var read = LoadOrderInterop.Collect(entries, unreadable);

        return read.Entries.Count == 0
            ? LoadOrderFileRead.Unreadable(Strings.Current["Core.Interop.Mo2ModListFile.NoModules"])
            : read;
    }

    // The modlist.txt text for this environment (BEM order, first loads first). With the profile's
    // existing text, the lines of mods that carry modules are re-sequenced into the slots those lines
    // already held and every other line (texture packs, separators, unmanaged mods) stays where it is.
    // A module with no folder in the map is returned as Unrepresentable.
    public static LoadOrderFileWrite Write(
        ModuleEnvironment environment,
        IReadOnlyDictionary<string, IReadOnlyList<string>> folderModules,
        string? existing = null)
    {
        ArgumentNullException.ThrowIfNull(environment);
        ArgumentNullException.ThrowIfNull(folderModules);

        var moduleToFolder = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);

        foreach (var (folder, modules) in folderModules)
            foreach (var module in modules)
                moduleToFolder.TryAdd(module, folder);

        var position = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
        var enabled = new Dictionary<string, bool>(StringComparer.OrdinalIgnoreCase);
        var unrepresentable = new List<string>();

        for (var i = 0; i < environment.Entries.Count; i++)
        {
            var entry = environment.Entries[i];

            if (!moduleToFolder.TryGetValue(entry.Id.Value, out var folder))
            {
                if (!entry.IsOfficial)
                    unrepresentable.Add(entry.Id.Value);

                continue;
            }

            // A folder with several modules sits at its first module's place and is on if any is.
            position.TryAdd(folder, i);
            enabled[folder] = enabled.GetValueOrDefault(folder) || entry.IsEnabled;
        }

        // Highest priority (latest load position) first.
        var sequence = position.OrderByDescending(p => p.Value).Select(p => p.Key).ToList();
        var lines = new List<string>();

        if (string.IsNullOrWhiteSpace(existing))
        {
            lines.Add(Header);
            lines.AddRange(sequence.Select(f => Line(enabled[f], f)));
        }
        else
        {
            var old = existing.TrimStart('﻿').Replace("\r\n", "\n").Split('\n').ToList();

            while (old.Count > 0 && old[^1].Length == 0)
                old.RemoveAt(old.Count - 1);

            var slots = new List<int>();

            for (var i = 0; i < old.Count; i++)
                if (old[i].Length > 1 && old[i][0] is '+' or '-' && position.ContainsKey(old[i][1..].Trim()))
                    slots.Add(i);

            var placed = slots.Select(s => old[s][1..].Trim()).ToHashSet(StringComparer.OrdinalIgnoreCase);
            var queue = new Queue<string>(sequence.Where(placed.Contains));

            foreach (var slot in slots)
            {
                var folder = queue.Dequeue();
                old[slot] = Line(enabled[folder], folder);
            }

            lines.AddRange(old);

            // A mod folder the profile never listed goes on top, where MO2 puts the newest priority.
            lines.InsertRange(
                lines.Count > 0 && lines[0].StartsWith('#') ? 1 : 0,
                sequence.Where(f => !placed.Contains(f)).Select(f => Line(enabled[f], f)));
        }

        return new LoadOrderFileWrite(string.Join("\r\n", lines) + "\r\n", unrepresentable);
    }

    private static string Line(bool on, string folder) => (on ? "+" : "-") + folder;

    private static List<(bool Enabled, string Name)> ParseLines(string text)
    {
        var lines = new List<(bool, string)>();

        foreach (var raw in text.TrimStart('﻿').Split('\n'))
        {
            var line = raw.Trim();

            if (line.Length < 2 || line[0] is not ('+' or '-'))
                continue;

            lines.Add((line[0] == '+', line[1..].Trim()));
        }

        return lines;
    }
}
